"""Follow-up automation — drafts only, human approval required.

HUMAN-APPROVAL GATE (non-negotiable, see docs/product-requirements.md §6):

- ``draft_followup()`` / ``generate_draft_for_claim()`` /
  ``generate_followup_drafts_for_overdue()`` create drafts. They NEVER
  send anything. Every draft is stored with ``status="draft"``.
- ``approve_followup()`` records who approved it and when — that is
  the explicit approval record. ``reject_followup()`` records a
  rejection the same way.
- ``send_followup()`` raises ``ApprovalRequiredError`` unless the draft
  is approved. There is no code path in this repo that sends an email
  without an explicit approval record.
- The starter's send implementation is a logged no-op: no SMTP / email
  provider is configured. Wiring a real transport is a deliberate,
  reviewed step — it must keep calling ``approve_followup()`` first
  and must write an audit-log row (roadmap Days 61–75).

Approval queue: drafts with ``status="draft"`` are the queue, listed
by GET /followups?status=draft. Approval / rejection are separate
endpoints (see api/followups.py) and are blocked for the ``viewer``
role (see services/auth.py).
"""
from dataclasses import dataclass, field
from datetime import date, datetime, timezone

from models.models import ChargeStatus, ClaimStatus
from services import audit_log, claims_service


class ApprovalRequiredError(Exception):
    """Raised when sending is attempted without human approval."""


@dataclass
class FollowUpDraft:
    id: str
    claim_id: str
    to: str
    subject: str
    body: str
    status: str = "draft"  # draft | approved | rejected | sent
    approved_by: str | None = None
    approved_at: str | None = None
    rejected_by: str | None = None
    rejected_at: str | None = None
    rejection_reason: str | None = None
    sent_at: str | None = None


_DRAFTS: dict[str, FollowUpDraft] = {}


def _evidence_summary(claim_id: str) -> str:
    claim = claims_service.get_claim(claim_id)
    if claim is None:
        return "Evidence: claim not found."
    charges = [c for c in claims_service.SAMPLE_CHARGES if c.id in claim.charge_ids]
    lines = []
    for c in charges:
        evidence = "evidence on file" if c.status != ChargeStatus.EVIDENCE_MISSING else "EVIDENCE MISSING"
        lines.append(f"- {c.type.value}: ${c.amount:.2f} — {c.description} ({evidence})")
    return "\n".join(lines) if lines else "Evidence: no charges on this claim."


def draft_followup(claim_id: str, to: str, subject: str, body: str, actor: str = "system") -> FollowUpDraft:
    """Create a follow-up draft. Does NOT send anything."""
    draft = FollowUpDraft(
        id=f"fu_{len(_DRAFTS) + 1:03d}",
        claim_id=claim_id,
        to=to,
        subject=subject,
        body=body,
    )
    _DRAFTS[draft.id] = draft
    audit_log.log_event(actor, "draft.generated", "followup", draft.id,
                        detail=f"Draft for claim {claim_id} to {to}")
    return draft


def generate_draft_for_claim(claim_id: str, to: str | None = None, actor: str = "system") -> FollowUpDraft:
    """Generate a draft follow-up for one claim, with amount, deadline,
    and evidence summary in the body. Saved as DRAFT only."""
    claim = claims_service.get_claim(claim_id)
    if claim is None:
        raise ValueError(f"Unknown claim: {claim_id}")
    to = to or f"billing@{claim.counterparty.lower().replace(' ', '').replace('.', '')}.example.com"
    subject = (
        f"Follow-up: Claim {claim.id} — ${claim.total_claimed:.2f} "
        f"— filing deadline {claim.filing_deadline.isoformat()}"
    )
    body = (
        f"Hello,\n\n"
        f"We are following up on claim {claim.id} for shipment {claim.shipment_id} "
        f"({claim.counterparty}).\n\n"
        f"Amount claimed: ${claim.total_claimed:.2f}\n"
        f"Amount recovered so far: ${claim.total_recovered:.2f}\n"
        f"Filing deadline: {claim.filing_deadline.isoformat()}\n"
        f"Claim status: {claim.status.value}\n\n"
        f"Charges and evidence:\n{_evidence_summary(claim_id)}\n\n"
        f"Please confirm receipt and advise on reimbursement timing.\n\n"
        f"[DRAFT — requires human approval before sending. "
        f"Generated by ClaimKit; no email has been sent.]\n"
    )
    return draft_followup(claim_id, to, subject, body, actor=actor)


def generate_followup_drafts_for_overdue(
    as_of: date | None = None, actor: str = "system"
) -> list[FollowUpDraft]:
    """Generate one draft per overdue / unpaid claim.

    A claim qualifies when it is unpaid (draft / ready / submitted /
    partially_paid) and its filing deadline is past or within 7 days.
    Paid and denied claims are skipped. A claim that already has a
    draft (any status) is skipped, so re-running never duplicates.
    """
    as_of = as_of or date.today()
    unpaid = (ClaimStatus.DRAFT, ClaimStatus.READY, ClaimStatus.SUBMITTED, ClaimStatus.PARTIALLY_PAID)
    drafts: list[FollowUpDraft] = []
    for claim in claims_service.list_claims():
        if claim.status not in unpaid:
            continue
        if (claim.filing_deadline - as_of).days > 7:
            continue
        if any(d.claim_id == claim.id for d in _DRAFTS.values()):
            continue
        drafts.append(generate_draft_for_claim(claim.id, actor=actor))
    return drafts


def approve_followup(draft_id: str, approved_by: str) -> FollowUpDraft:
    """Human approval step. Records approver + timestamp."""
    draft = _DRAFTS[draft_id]
    if draft.status == "sent":
        raise ValueError("Follow-up already sent; cannot re-approve.")
    if draft.status == "rejected":
        raise ValueError("Follow-up was rejected; create a new draft instead.")
    draft.status = "approved"
    draft.approved_by = approved_by
    draft.approved_at = datetime.now(timezone.utc).isoformat()
    audit_log.log_event(approved_by, "draft.approved", "followup", draft.id,
                        detail=f"Approved draft for claim {draft.claim_id}")
    return draft


def reject_followup(draft_id: str, rejected_by: str, reason: str | None = None) -> FollowUpDraft:
    """Human rejection step. Records rejecter, timestamp, and reason."""
    draft = _DRAFTS[draft_id]
    if draft.status == "sent":
        raise ValueError("Follow-up already sent; cannot reject.")
    draft.status = "rejected"
    draft.rejected_by = rejected_by
    draft.rejected_at = datetime.now(timezone.utc).isoformat()
    draft.rejection_reason = reason
    audit_log.log_event(rejected_by, "draft.rejected", "followup", draft.id,
                        detail=f"Rejected draft for claim {draft.claim_id}: {reason or ''}")
    return draft


def send_followup(draft_id: str, actor: str = "system") -> FollowUpDraft:
    """Send an approved follow-up — approval gate enforced here.

    Raises ApprovalRequiredError for any draft that is not approved,
    and logs the blocked attempt to the audit log.
    The starter implementation logs the send and marks it sent; it does
    NOT contact any mail server. Replace the no-op with a real provider
    only after review, keeping this gate in place.
    """
    draft = _DRAFTS[draft_id]
    if draft.status != "approved":
        audit_log.log_event(actor, "draft.send_blocked", "followup", draft.id,
                            detail=f"Send blocked: status is '{draft.status}', not 'approved'")
        raise ApprovalRequiredError(
            f"Follow-up {draft_id} is '{draft.status}', not 'approved'. "
            "A human must approve it before it can be sent."
        )
    # NO-OP SEND (starter): log only, no SMTP / email provider configured.
    print(f"[claimkit] SEND (logged no-op) follow-up {draft.id} to {draft.to}: {draft.subject}")
    draft.status = "sent"
    draft.sent_at = datetime.now(timezone.utc).isoformat()
    audit_log.log_event(actor, "draft.sent", "followup", draft.id,
                        detail=f"Sent (logged no-op) to {draft.to}")
    return draft


def get_draft(draft_id: str) -> FollowUpDraft | None:
    return _DRAFTS.get(draft_id)


def list_drafts(status: str | None = None) -> list[FollowUpDraft]:
    """The approval queue: all drafts, or only those with a given status."""
    drafts = list(_DRAFTS.values())
    return [d for d in drafts if status is None or d.status == status]


def clear() -> None:
    """Test helper only — never expose via the API."""
    _DRAFTS.clear()
